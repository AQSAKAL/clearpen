// Copies drizzle-kit's SQL migrations into src/migrations.ts. The desktop app
// has no file system to read them from, so they ship inside the bundle.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'migrations');
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const entries = files.map((f) => {
  const sql = fs.readFileSync(path.join(dir, f), 'utf8').trim();
  return `  {\n    id: ${JSON.stringify(f.replace(/\.sql$/, ''))},\n    sql: ${JSON.stringify(sql)},\n  },`;
});

fs.writeFileSync(
  path.join(root, 'src', 'migrations.ts'),
  `// Generated by scripts/embed-migrations.mjs from migrations/*.sql — don't edit.\n\nexport interface Migration {\n  id: string;\n  sql: string;\n}\n\nexport const MIGRATIONS: Migration[] = [\n${entries.join('\n')}\n];\n`,
);
console.log(`Embedded ${files.length} migration(s).`);
